// Generates or checks src/manifest.ts — the zod-free projection of the route registry used by browser clients.
//   node scripts/manifest.mjs write   → regenerate
//   node scripts/manifest.mjs check   → fail if the committed file is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { routes } = await import(pathToFileURL(join(root, 'dist', 'index.js')).href);
const target = join(root, 'src', 'manifest.ts');
const mode = process.argv[2] ?? 'check';

const lines = Object.entries(routes).map(([id, s]) => {
  const parts = [`method: '${s.method}'`, `path: '${s.path}'`];
  if (s.idempotent) parts.push('idempotent: true');
  if (s.bodyKind) parts.push(`bodyKind: '${s.bodyKind}'`);
  if (s.responseKind) parts.push(`responseKind: '${s.responseKind}'`);
  return `  '${id}': { ${parts.join(', ')} },`;
});

const generated = `// GENERATED by scripts/manifest.mjs from routes.ts — do not edit. Run: pnpm --filter @labpass/contracts generate
import type { RouteId } from './routes';
import type { ManifestEntry } from './client';

export const routeManifest: Record<RouteId, ManifestEntry> = {
${lines.join('\n')}
};
`;

if (mode === 'write') {
  writeFileSync(target, generated);
  console.log(`manifest.ts written: ${lines.length} routes`);
} else {
  const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== generated) {
    console.error('src/manifest.ts is stale. Run: pnpm --filter @labpass/contracts generate');
    process.exit(1);
  }
  console.log('manifest.ts is up to date');
}
