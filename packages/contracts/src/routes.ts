export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';
/** public: no auth · admin: session cookie + minRole · kiosk: device bearer token · student: student bearer token */
export type AuthKind = 'public' | 'admin' | 'kiosk' | 'student';

export interface RateLimit {
  key: 'ip' | 'kiosk' | 'student' | 'admin' | 'body';
  limit: number;
  windowSec: number;
  /** Optional body field used as part of the key (e.g. matricule) when key = 'body'. */
  field?: string;
}

export interface RouteSpec {
  method: HttpMethod;
  path: string;
  auth: AuthKind;
  minRole?: AdminRole;
  summary: string;
  tag: string;
  params?: z.ZodObject;
  query?: z.ZodObject;
  body?: z.ZodType;
  response: z.ZodType | null;
  status?: number;
  /** Requires an `Idempotency-Key` header; the effect is stored in the same DB transaction (ARCH §5 F5). */
  idempotent?: boolean;
  /** Writes an AuditLog entry (invariant I7). */
  audited?: boolean;
  bodyKind?: 'json' | 'binary';
  responseKind?: 'json' | 'csv' | 'empty' | 'text' | 'binary';
  rateLimit?: RateLimit;
}

