// Emits CSS variables, a Tailwind v4 theme and a JSON snapshot from the compiled tokens (dist/index.js).
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const { tokens } = await import(pathToFileURL(join(dist, 'index.js')).href);
const { palette, themes, font, fontSize, tracking, radius, shadow } = tokens;

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const themeVars = (t) =>
  Object.entries(t)
    .map(([k, v]) => `  --lp-${kebab(k)}: ${v};`)
    .join('\n');

const paletteVars = Object.entries(palette)
  .flatMap(([group, shades]) => Object.entries(shades).map(([k, v]) => `  --lp-${group}-${k}: ${v};`))
  .join('\n');

const css = `/* Generated by @labpass/design-tokens — do not edit. */
:root {
${paletteVars}
${themeVars(themes.light)}
  --lp-font-sans: ${font.sans};
  --lp-font-display: ${font.display};
  --lp-font-mono: ${font.mono};
  --lp-shadow-float: ${shadow.float};
  --lp-shadow-glow: ${shadow.glow};
  color-scheme: light;
}
:root[data-theme='dark'],
.theme-dark {
${themeVars(themes.dark)}
  color-scheme: dark;
}
`;

const semantic = Object.keys(themes.light)
  .map((k) => `  --color-${kebab(k)}: var(--lp-${kebab(k)});`)
  .join('\n');
const paletteTheme = Object.entries(palette)
  .flatMap(([group, shades]) => Object.entries(shades).map(([k, v]) => `  --color-${group}-${k}: ${v};`))
  .join('\n');
const sizes = Object.entries(fontSize)
  .map(([k, v]) => `  --text-${k}: ${v / 16}rem;`)
  .join('\n');
const radii = Object.entries(radius)
  .map(([k, v]) => `  --radius-${k}: ${v}px;`)
  .join('\n');
const trackings = Object.entries(tracking)
  .map(([k, v]) => `  --tracking-${k}: ${v};`)
  .join('\n');

const theme = `/* Generated by @labpass/design-tokens — Tailwind v4 theme. Import after "tailwindcss". */
@theme inline {
${semantic}
  --font-sans: var(--lp-font-sans);
  --font-display: var(--lp-font-display);
  --font-mono: var(--lp-font-mono);
  --shadow-float: var(--lp-shadow-float);
  --shadow-glow: var(--lp-shadow-glow);
}
@theme {
${paletteTheme}
${sizes}
${radii}
${trackings}
}
`;

mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, 'tokens.css'), css);
writeFileSync(join(dist, 'theme.css'), theme);
writeFileSync(join(dist, 'tokens.json'), JSON.stringify(tokens, null, 2));
console.log('design-tokens: wrote tokens.css, theme.css, tokens.json');
